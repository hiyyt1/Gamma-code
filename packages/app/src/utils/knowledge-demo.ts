// Explicit copy remaps every reference; the catalog and existing spaces stay intact.
export function copyKnowledgeDemo(data: KnowledgeData, spaceID: string, now: string) {
  if (data.spaces.some((space) => space.id === spaceID)) throw new Error("duplicate")
  const id = (value: string) => `${spaceID}:${value}`
  const next = structuredClone(data)
  return {
    ...next,
    spaces: [...next.spaces, { ...demoKnowledge.spaces[0], id: spaceID, createdAt: now, updatedAt: now }],
    sources: [
      ...next.sources,
      ...demoKnowledge.sources.map((source) => ({
        ...structuredClone(source),
        id: id(source.id),
        spaceID,
        ...(source.documentID ? { documentID: id(source.documentID) } : {}),
        createdAt: now,
        updatedAt: now,
      })),
    ],
    relations: [
      ...next.relations,
      ...demoKnowledge.relations.map((edge) => ({
        ...structuredClone(edge),
        id: id(edge.id),
        spaceID,
        source: id(edge.source),
        target: id(edge.target),
      })),
    ],
  }
}
